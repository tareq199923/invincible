HARDER_IDS = (
    "long-chain-feature",
    "many-files-read",
    "glob-nested",
    "run-tests-report",
    "three-bugs-three-files",
    "ambiguous-edit",
    "crlf-edit",
    "wrong-path-recovery",
    "big-output-command",
    "denial-handling",
)


def _raw_tasks() -> dict[str, dict]:
    out: dict[str, dict] = {}
    for path in sorted(eval_runner.TASK_DIR.glob("*.yaml")):
        with open(path, encoding="utf-8") as fh:
            raw = yaml.safe_load(fh)
        if "harder" in raw.get("tags", []):
            out[raw["id"]] = raw
    return out


def _materialize(
    workspace: Path, files: dict[str, str], generate: list[dict] | None = None
) -> None:
    # Shared builder: identical bytes to live runs (CRLF preserved for
    # static files, LF for generated files).
    materialize_fixture(files, generate or [], workspace)


