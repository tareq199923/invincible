def test_b2_field_patterns():
    good = "FAILED=vault_sync ERROR=disk quota exceeded"
    assert _matches(r"FAILED=vault_sync\b", good)
    assert _matches(r"ERROR=disk quota exceeded", good)
    assert not _matches(r"FAILED=fail_safe", good)
    assert not _matches(r"FAILED=failover", good)
