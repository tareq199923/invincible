def test_many_files_non_bypassability():
    """No single line carries the true event; isolating it needs a req-id
    join across lines, and each single-pattern search floods."""
    built = build_retry_logs(_retry_spec())
    lines = [
        line for raw in built.values()
        for line in raw.decode("utf-8").splitlines()
    ]
    assert not any(
        "attempt=3" in line and "result=" in line for line in lines
    )
    attempt_ids = {
        line.split("req=")[1].split()[0]
        for line in lines if "attempt=3" in line
    }
    timeout_ids = {
        line.split("req=")[1].split()[0]
        for line in lines
        if line.rstrip().endswith("result=timeout")
    }
    assert len(attempt_ids) >= 15, len(attempt_ids)
    assert len(timeout_ids) >= 15, len(timeout_ids)
    attempt_of = {}
    for line in lines:
        if "attempt=" in line and "req=" in line:
            rid = line.split("req=")[1].split()[0]
            attempt_of.setdefault(rid, line)
    result_of = {}
    for line in lines:
        if line.startswith("req=") and "result=" in line:
            rid = line.split("req=")[1].split()[0]
            result_of.setdefault(rid, line)
    joined = sorted(
        rid for rid in attempt_ids & set(result_of)
        if "attempt=3" in attempt_of[rid]
        and result_of[rid].rstrip().endswith("result=timeout")
    )
    assert joined == ["q9z4"]
    meridian_lines = [line for line in lines if "meridian" in line]
    assert len(meridian_lines) >= 3
    delay_lines = [line for line in lines if "400" in line]
    assert len(delay_lines) == 1


# --- decoy / trap regex unit tests --------------------------------------------


def _matches(pattern: str, text: str) -> bool:
    import re

    return re.search(pattern, text, re.IGNORECASE) is not None


def test_b1_field_patterns():
    good = "SERVICE=meridian DELAY_MS=400"
    assert _matches(r"(?<![\w])SERVICE=meridian[ \t]+DELAY_MS=400\b", good)
    assert not _matches(
        r"(?<![\w])SERVICE=halcyon[ \t]+DELAY_MS=250", good)
    # Explaining the work by quoting the decoy policy line is fine as
    # long as the answer ends with the single-line meridian/400 answer.
    explained = (
        "policy service=halcyon retry_delay_ms=250 is only the decoy; "
        "the attempt-3 timeout is q9z4 on meridian.\n"
        "SERVICE=meridian DELAY_MS=400"
    )
    assert _matches(
        r"(?<![\w])SERVICE=meridian[ \t]+DELAY_MS=400\b", explained)
    assert not _matches(
        r"(?<![\w])SERVICE=halcyon[ \t]+DELAY_MS=250", explained)
    # A halcyon/250 answer fails both directions.
    wrong = "SERVICE=halcyon DELAY_MS=250"
    assert not _matches(
        r"(?<![\w])SERVICE=meridian[ \t]+DELAY_MS=400\b", wrong)
    assert _matches(
        r"(?<![\w])SERVICE=halcyon[ \t]+DELAY_MS=250", wrong)
    # Meridian in the wrong format fails: newline cannot join the pair,
    # and split lines do not form the single-line answer.
    assert not _matches(
        r"(?<![\w])SERVICE=meridian[ \t]+DELAY_MS=400\b",
        "SERVICE=meridian\nDELAY_MS=400")
    assert not _matches(
        r"(?<![\w])SERVICE=meridian[ \t]+DELAY_MS=400\b",
        "SERVICE=meridian")
    # Tab between fields is still one line, so it passes.
    assert _matches(
        r"(?<![\w])SERVICE=meridian[ \t]+DELAY_MS=400\b",
        "SERVICE=meridian\tDELAY_MS=400")


