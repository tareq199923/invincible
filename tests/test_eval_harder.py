# --- glob fixture integrity ---------------------------------------------------


def _glob_rule_match(rel: str) -> bool:
    import fnmatch

    if not (rel.startswith("tree/alpha/") or rel.startswith("tree/beta/")):
        return False
    base = rel.rsplit("/", 1)[-1]
    return fnmatch.fnmatchcase(base, "*_report.txt")


def test_glob_count_matches_fixture():
    raw = _raw_tasks()["glob-nested"]
    expected = sorted(rel for rel in raw["files"] if _glob_rule_match(rel))
    count_check = next(
        c for c in raw["checks"]
        if c["type"] == "final_text_contains" and "COUNT" in c["pattern"])
    assert count_check["pattern"] == f"COUNT={len(expected)}\\b"
    listed = sorted(
        c["pattern"] for c in raw["checks"]
        if c["type"] == "final_text_contains" and "COUNT" not in c["pattern"])
    assert len(listed) == len(expected)
    for pattern, rel in zip(listed, expected, strict=True):
        normalized = pattern.replace("[\\\\/]", "/").replace("\\.", ".")
        normalized = normalized.split("(?!", 1)[0]
        assert normalized.startswith(rel.split(".txt")[0]), (pattern, rel)


def test_glob_no_casefold_collision():
    import collections

    raw = _raw_tasks()["glob-nested"]
    by_dir: dict[str, list[str]] = collections.defaultdict(list)
    for rel in raw["files"]:
        parent, _, base = rel.rpartition("/")
        by_dir[parent].append(base.casefold())
    for parent, bases in by_dir.items():
        assert len(set(bases)) == len(bases), f"collision in {parent}"


