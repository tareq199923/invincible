# --- two-sided fairness -------------------------------------------------------


@pytest.mark.parametrize("task_id", sorted(HARDER_IDS))
def test_fixture_fails_without_solution(task_id: str, tmp_path: Path):
    """Unmodified fixture + empty answer must NOT pass."""
    raw = _raw_tasks()[task_id]
    _materialize(tmp_path, raw.get("files", {}), raw.get("generate", []))
    passed, _ = graders.grade_all(
        raw["checks"], workspace=tmp_path, final_text="",
        tool_counts={})
    assert passed is False, f"{task_id}: fixture passes with no solution"


@pytest.mark.parametrize("task_id", sorted(HARDER_IDS))
def test_reference_solution_passes(task_id: str, tmp_path: Path):
    """Applying the reference solution (files + deletes + final text,
    shell_check run for real) must pass every check."""
    raw = _raw_tasks()[task_id]
    _materialize(tmp_path, raw.get("files", {}), raw.get("generate", []))
    ref = raw["reference"]
    for stage in ref.get("stages", []):
        _materialize(tmp_path, stage)
    _materialize(tmp_path, ref.get("files", {}))
    for rel in ref.get("delete", []):
        (tmp_path / rel).unlink(missing_ok=True)
    passed, results = graders.grade_all(
        raw["checks"], workspace=tmp_path,
        final_text=ref.get("final_text", ""), tool_counts={})
    assert passed is True, (
        f"{task_id}: reference fails: "
        + str([(r["type"], r["passed"], r["reason"]) for r in results])
    )


def _clear_pycache(workspace: Path) -> None:
    import shutil

    # Same-size rewrites milliseconds apart can fall inside one mtime
    # tick, letting CPython trust a stale .pyc. Real agent edits are
    # seconds apart (approval round-trips); the hermetic test must not
    # depend on tick granularity, so drop bytecode caches between runs.
    shutil.rmtree(workspace / "__pycache__", ignore_errors=True)


def test_three_bugs_staged_fairness(tmp_path: Path):
    """Cascade proof: each stage still fails (on the NEXT bug) until all
    three are fixed. Reasons pin which assert fired."""
    raw = _raw_tasks()["three-bugs-three-files"]
    ref = raw["reference"]
    assert len(ref["stages"]) == 2
    _materialize(tmp_path, raw.get("files", {}))
    passed, _ = graders.grade_all(
        raw["checks"], workspace=tmp_path, final_text="",
        tool_counts={})
    assert passed is False
    _materialize(tmp_path, ref["stages"][0])
    _clear_pycache(tmp_path)
    passed, results = graders.grade_all(
        raw["checks"], workspace=tmp_path, final_text="",
        tool_counts={})
    assert passed is False, "fix-1-only must still fail"
    assert "shout" in results[0]["reason"], results
    _materialize(tmp_path, ref["stages"][1])
    _clear_pycache(tmp_path)
    passed, results = graders.grade_all(
        raw["checks"], workspace=tmp_path, final_text="",
        tool_counts={})
    assert passed is False, "fix-1+2 must still fail"
    assert "checkout" in results[0]["reason"], results


